import "reflect-metadata";
import { test, after } from "node:test";
import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { prisma, PrismaClient, type Prisma } from "@workspace/saudisensei-database";
import { LmsStore, type Actor } from "../src/modules/courses/lms.store.js";
import { CoursesService } from "../src/modules/courses/courses.service.js";
import { StructureService } from "../src/modules/courses/structure.service.js";
import { EnrollmentsService } from "../src/modules/enrollments/enrollments.service.js";
import { ProgressService } from "../src/modules/progress/progress.service.js";
import { LearningService } from "../src/modules/progress/learning.service.js";
import { LmsQueries } from "../src/modules/dashboards/lms.queries.js";
import { listInput } from "../src/modules/courses/lms.schemas.js";

after(async () => { await prisma.$disconnect(); });
const rollback = new Error("ROLLBACK_FIXTURES");
test("real PostgreSQL LMS lifecycle preserves history and denies unavailable content", async () => {
  let verified = false;
  try {
    await prisma.$transaction(async (tx) => {
      let savepoint = 0;
      const db = new Proxy(tx, { get(target, key) {
        if (key === "$transaction") return async (work: (tx: Prisma.TransactionClient) => Promise<unknown>) => {
          const name = `lms_test_${++savepoint}`;
          await tx.$executeRawUnsafe(`SAVEPOINT ${name}`);
          try { const result = await work(tx); await tx.$executeRawUnsafe(`RELEASE SAVEPOINT ${name}`); return result; }
          catch (error) { await tx.$executeRawUnsafe(`ROLLBACK TO SAVEPOINT ${name}`); throw error; }
        };
        const value = Reflect.get(target, key);
        return typeof value === "function" ? value.bind(target) : value;
      } }) as unknown as PrismaClient;
      const store = new LmsStore(db);
      const courses = new CoursesService(store), structure = new StructureService(store);
      const enrollments = new EnrollmentsService(store), progress = new ProgressService(store);
      const learning = new LearningService(store, enrollments, progress), queries = new LmsQueries(store, progress);
      const user = await tx.user.create({ data: { email: `${randomUUID()}@fixture.invalid`, displayName: "Rollback fixture" } });
      const second = await tx.user.create({ data: { email: `${randomUUID()}@fixture.invalid`, displayName: "Second fixture" } });
      const role = await tx.role.upsert({ where: { name: "student" }, create: { name: "student" }, update: {} });
      await tx.userRole.createMany({ data: [user, second].map((u) => ({ userId: u.id, roleId: role.id })) });
      const actor: Actor = { user: { id: user.id, email: user.email, displayName: user.displayName, status: "active", roles: ["student", "admin"], preferredLocale: "ar" }, requestId: randomUUID() };
      const course = await courses.create(actor, { title: "العربية Course", description: "Current curriculum" });
      const other = await courses.create(actor, { title: "Other", description: "" });
      let revision = course.editRevision;
      const chapter = await structure.createChapter(course.id, actor, { title: "Chapter", expectedRevision: revision });
      revision = chapter.editRevision;
      const a = await structure.createLesson(chapter.id, actor, { title: "A", body: "# Heading\n`code`", isRequired: true, expectedRevision: revision });
      revision = a.editRevision;
      const b = await structure.createLesson(chapter.id, actor, { title: "B", body: "- Text", isRequired: true, expectedRevision: revision });
      revision = b.editRevision;
      const enrollment = await enrollments.grant(actor, course.id, user.id);
      assert.equal((await enrollments.grant(actor, course.id, user.id)).id, enrollment.id);
      await assert.rejects(learning.course(user.id, course.id), { message: "RESOURCE_NOT_FOUND" });
      assert.equal((await queries.myCourses(user.id, listInput.parse({}))).total, 0);
      await assert.rejects(courses.transition(course.id, actor, revision, "published"), { message: "PUBLISHED_STRUCTURE_REQUIRED" });
      revision = (await structure.editLesson(a.id, actor, { expectedRevision: revision, status: "published" })).editRevision;
      revision = (await structure.editChapter(chapter.id, actor, { expectedRevision: revision, status: "published" })).editRevision;
      revision = (await courses.transition(course.id, actor, revision, "published")).editRevision;
      await assert.rejects(courses.edit(course.id, actor, { title: "stale", expectedRevision: revision - 1 }), { message: "COURSE_CHANGED" });
      await assert.rejects(learning.lesson(second.id, a.id), { message: "RESOURCE_NOT_FOUND" });
      await assert.rejects(learning.lesson(user.id, b.id), { message: "RESOURCE_NOT_FOUND" });
      const first = await learning.complete(user.id, a.id);
      assert.equal(first.progress.percentage, 100);
      assert.equal((await learning.complete(user.id, a.id)).completedAt.getTime(), first.completedAt.getTime());
      revision = (await structure.editLesson(b.id, actor, { expectedRevision: revision, status: "published" })).editRevision;
      assert.equal((await learning.getProgress(user.id, course.id)).percentage, 50);
      const outline = await learning.course(user.id, course.id);
      assert.equal("body" in outline.chapters[0]!.lessons[0]!, false);
      assert.equal(outline.chapters[0]!.lessons[0]!.completed, true);
      revision = (await structure.reorder("lesson", chapter.id, actor, { orderedIds: [b.id, a.id], expectedRevision: revision })).editRevision;
      assert.equal((await learning.getProgress(user.id, course.id)).continueLessonId, b.id);
      revision = (await structure.editLesson(a.id, actor, { expectedRevision: revision, title: "Edited" })).editRevision;
      assert.equal((await learning.lesson(user.id, a.id)).completed, true);
      await assert.rejects(structure.reorder("lesson", chapter.id, actor, { orderedIds: [a.id, other.id], expectedRevision: revision }), { message: "INVALID_ORDER" });
      revision = (await structure.editLesson(b.id, actor, { expectedRevision: revision, isRequired: false })).editRevision;
      assert.equal((await learning.getProgress(user.id, course.id)).percentage, 100);
      await learning.complete(user.id, b.id);
      assert.equal((await learning.getProgress(user.id, course.id)).totalRequired, 1);
      await enrollments.change(actor, enrollment.id, "revoked");
      await assert.rejects(learning.complete(user.id, a.id), { message: "RESOURCE_NOT_FOUND" });
      assert.equal((await queries.studentDashboard(user.id)).totalCourses, 0);
      assert.equal((await enrollments.grant(actor, course.id, user.id)).id, enrollment.id);
      assert.equal((await learning.getProgress(user.id, course.id)).percentage, 100);
      revision = (await structure.editLesson(a.id, actor, { expectedRevision: revision, status: "draft" })).editRevision;
      assert.equal((await learning.getProgress(user.id, course.id)).percentage, 0);
      assert.equal((await learning.getProgress(user.id, course.id)).isCompleted, false);
      revision = (await structure.editLesson(a.id, actor, { expectedRevision: revision, status: "published" })).editRevision;
      assert.equal((await learning.getProgress(user.id, course.id)).percentage, 100);
      revision = (await structure.editChapter(chapter.id, actor, { expectedRevision: revision, status: "draft" })).editRevision;
      await assert.rejects(learning.lesson(user.id, a.id), { message: "RESOURCE_NOT_FOUND" });
      assert.equal((await learning.getProgress(user.id, course.id)).totalRequired, 0);
      revision = (await structure.editChapter(chapter.id, actor, { expectedRevision: revision, status: "published" })).editRevision;
      revision = (await courses.transition(course.id, actor, revision, "draft")).editRevision;
      await assert.rejects(learning.getProgress(user.id, course.id), { message: "RESOURCE_NOT_FOUND" });
      revision = (await courses.transition(course.id, actor, revision, "published")).editRevision;
      const courseProgress = await learning.getProgress(user.id, course.id);
      const dashboard = await queries.studentDashboard(user.id);
      assert.equal(dashboard.completedRequired, courseProgress.completedRequired);
      assert.equal((await queries.enrollments(listInput.parse({ courseId: course.id }))).items[0]!.progress.percentage, courseProgress.percentage);
      await tx.enrollment.update({ where: { id: enrollment.id }, data: { enrolledAt: new Date(Date.now() - 10000), expiresAt: new Date(Date.now() - 5000) } });
      await assert.rejects(learning.lesson(user.id, a.id), { message: "RESOURCE_NOT_FOUND" });
      await enrollments.grant(actor, course.id, user.id);
      revision = (await structure.editLesson(a.id, actor, { expectedRevision: revision, status: "archived" })).editRevision;
      await assert.rejects(structure.editLesson(a.id, actor, { expectedRevision: revision, status: "draft" }), { message: "ARCHIVED_READ_ONLY" });
      assert.equal(await tx.lessonCompletion.count({ where: { enrollmentId: enrollment.id } }), 2);
      const archivedLesson = await tx.lesson.findUniqueOrThrow({ where: { id: a.id } });
      const activeLessons = await tx.lesson.findMany({ where: { chapterId: chapter.id, status: { not: "archived" } }, orderBy: { position: "desc" } });
      revision = (await structure.reorder("lesson", chapter.id, actor, { expectedRevision: revision, orderedIds: activeLessons.map((l) => l.id) })).editRevision;
      assert.deepEqual(await tx.lesson.findUniqueOrThrow({ where: { id: a.id } }), archivedLesson);
      const archivedSibling = await structure.createChapter(course.id, actor, { expectedRevision: revision, title: "Read-only sibling" });
      revision = archivedSibling.editRevision;
      revision = (await structure.editChapter(archivedSibling.id, actor, { expectedRevision: revision, status: "archived" })).editRevision;
      const archivedChapter = await tx.chapter.findUniqueOrThrow({ where: { id: archivedSibling.id } });
      revision = (await structure.reorder("chapter", course.id, actor, { expectedRevision: revision, orderedIds: [chapter.id] })).editRevision;
      assert.deepEqual(await tx.chapter.findUniqueOrThrow({ where: { id: archivedSibling.id } }), archivedChapter);
      revision = (await courses.transition(course.id, actor, revision, "archived")).editRevision;
      await assert.rejects(enrollments.grant(actor, course.id, second.id), { message: "ARCHIVED_READ_ONLY" });
      await assert.rejects(courses.edit(course.id, actor, { expectedRevision: revision, title: "no" }), { message: "ARCHIVED_READ_ONLY" });
      assert.equal((await queries.myCourses(user.id, listInput.parse({}))).total, 0);
      assert.ok(await tx.auditLog.count({ where: { actorUserId: user.id } }) >= 15);
      // Force audit failure and verify both data change and revision roll back.
      const badActor = { ...actor, user: { ...actor.user!, id: randomUUID() } };
      await assert.rejects(courses.edit(other.id, badActor, { expectedRevision: 0, title: "Must rollback" }));
      assert.equal((await courses.get(other.id)).title, "Other");
      assert.equal((await courses.get(other.id)).editRevision, 0);
      verified = true;
      throw rollback;
    }, { timeout: 120000 });
  } catch (error) { if (error !== rollback) throw error; }
  assert.equal(verified, true);
});
